/**
 * Creates infra/local/.env with fresh random secrets for the local stack: database password, the
 * login signing key, the first administrator's password and the pseudonymisation keys. It never
 * overwrites an existing file (that would lock you out of an existing database) and never prints a
 * secret: open the file to read the administrator password.
 */
import { generateKeyPairSync, randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const target = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'infra', 'local', '.env');

if (existsSync(target)) {
  process.stdout.write(
    `${target} already exists: left unchanged. Delete it to create new secrets.\n`,
  );
  process.exit(0);
}

const secret = (bytes) => randomBytes(bytes).toString('base64url');
const { privateKey } = generateKeyPairSync('rsa', {
  modulusLength: 2048,
  privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
  publicKeyEncoding: { type: 'spki', format: 'pem' },
});

const lines = [
  '# Local development secrets. Generated by tools/local/make-env.mjs. Never commit this file.',
  `POSTGRES_PASSWORD=${secret(18)}`,
  // The signing key is one line: line breaks are written as \n, which the Identity Service accepts.
  `JWT_PRIVATE_KEY_PEM="${privateKey.trim().replace(/\n/g, '\\n')}"`,
  'ADMIN_EMAIL=admin@example.com',
  `ADMIN_PASSWORD=${secret(18)}`,
  `INSIGHT_PSEUDONYM_KEY=${secret(36)}`,
  `LOG_PSEUDONYM_SALT=${secret(24)}`,
  '',
];
writeFileSync(target, lines.join('\n'), { mode: 0o600 });
process.stdout.write(
  `Created ${target}\nThe administrator's email and password are in that file.\n`,
);
